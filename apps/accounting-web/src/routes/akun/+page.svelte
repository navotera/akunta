<script lang="ts">
  import { onMount } from 'svelte';
  import { goto } from '$app/navigation';
  import { auth } from '$lib/stores/auth.svelte.js';
  import { accountApi, type Account, type AccountInput } from '$lib/api/account.js';
  import { ApiError } from '$lib/api/client.js';
  import CoaTreeNode from '$lib/components/coa/CoaTreeNode.svelte';
  import AccountDescriptionTooltip from '$lib/components/coa/AccountDescriptionTooltip.svelte';
  import Combobox, { type ComboOption } from '$lib/components/ui/Combobox.svelte';

  type ViewMode = 'list' | 'tree' | 'tview';

  interface TreeNode {
    account: Account;
    children: TreeNode[];
  }

  let items = $state<Account[]>([]);
  let viewMode = $state<ViewMode>('list');
  let treeSearch = $state('');
  let listSearch = $state('');
  let filterOpen = $state(false);
  let filterType = $state('');
  let filterNormalBalance = $state('');
  let filterAvailability = $state('');
  let filterStatus = $state('');
  let filterPostable = $state('');
  let filterFake = $state('');
  let loading = $state(true);
  let error = $state<string | null>(null);

  const TYPE_LABEL: Record<string, string> = {
    asset: 'Aktiva',
    liability: 'Kewajiban',
    equity: 'Ekuitas',
    revenue: 'Pendapatan',
    expense: 'Biaya',
    cogs: 'HPP',
    contra_asset: 'Kontra Aktiva',
    contra_liability: 'Kontra Kewajiban',
    contra_equity: 'Kontra Ekuitas',
    contra_revenue: 'Kontra Pendapatan',
  };

  const AVAILABILITY_LABEL: Record<string, string> = {
    intern: 'Intern',
    fiskal: 'Fiskal',
    both: 'Intern & Fiskal',
  };

  const filtered = $derived.by(() => {
    if (!treeSearch.trim()) return items;
    const q = treeSearch.trim().toLowerCase();
    return items.filter(
      (a) =>
        a.code.toLowerCase().includes(q) ||
        a.name.toLowerCase().includes(q) ||
        (a.description?.toLowerCase().includes(q) ?? false),
    );
  });

  const listFiltered = $derived.by(() => {
    const q = listSearch.trim().toLowerCase();

    return items.filter((account) => {
      const matchesSearch =
        !q ||
        account.code.toLowerCase().includes(q) ||
        account.name.toLowerCase().includes(q) ||
        (account.description?.toLowerCase().includes(q) ?? false);

      return (
        matchesSearch &&
        (!filterType || account.type === filterType) &&
        (!filterNormalBalance || account.normal_balance === filterNormalBalance) &&
        (!filterAvailability || account.availability === filterAvailability) &&
        (!filterStatus || (filterStatus === 'active' ? account.is_active : !account.is_active)) &&
        (!filterPostable ||
          (filterPostable === 'postable' ? account.is_postable : !account.is_postable)) &&
        (!filterFake || (filterFake === 'fake' ? account.is_fake : !account.is_fake))
      );
    });
  });

  const activeFilterCount = $derived(
    [
      filterType,
      filterNormalBalance,
      filterAvailability,
      filterStatus,
      filterPostable,
      filterFake,
    ].filter(Boolean).length,
  );

  function buildTree(rows: Account[]): TreeNode[] {
    const byParent = new Map<string, Account[]>();
    for (const a of rows) {
      const k = a.parent_account_id ?? '__root__';
      if (!byParent.has(k)) byParent.set(k, []);
      byParent.get(k)!.push(a);
    }
    const build = (parent: string | null): TreeNode[] =>
      (byParent.get(parent ?? '__root__') ?? [])
        .sort((a, b) => a.code.localeCompare(b.code))
        .map((a) => ({ account: a, children: build(a.id) }));
    return build(null);
  }

  function buildSideTree(rows: Account[], side: 'debit' | 'credit'): TreeNode[] {
    const subset = rows.filter((a) => a.normal_balance === side);
    const ids = new Set(subset.map((a) => a.id));
    const byParent = new Map<string, Account[]>();
    for (const a of subset) {
      const parentKey =
        a.parent_account_id && ids.has(a.parent_account_id) ? a.parent_account_id : '__root__';
      if (!byParent.has(parentKey)) byParent.set(parentKey, []);
      byParent.get(parentKey)!.push(a);
    }
    const build = (parent: string | null): TreeNode[] =>
      (byParent.get(parent ?? '__root__') ?? [])
        .sort((a, b) => a.code.localeCompare(b.code))
        .map((a) => ({ account: a, children: build(a.id) }));
    return build(null);
  }

  const treeData = $derived(buildTree(filtered));
  const debitTree = $derived(buildSideTree(filtered, 'debit'));
  const creditTree = $derived(buildSideTree(filtered, 'credit'));

  let editing = $state<Account | null>(null);
  let creating = $state(false);
  let form = $state<AccountInput>({
    code: '',
    name: '',
    description: '',
    type: 'asset',
    normal_balance: 'debit',
    parent_account_id: null,
    is_postable: true,
    is_active: true,
    availability: 'intern',
    legal_basis: '',
  });
  let formErrors = $state<Record<string, string[]> | null>(null);
  let saving = $state(false);
  let codeAutoGenerated = $state(true);
  const editingId = $derived(editing?.id);
  const editingHasChildren = $derived(
    editingId ? items.some((account) => account.parent_account_id === editingId) : false,
  );

  function isDescendant(accountId: string, ancestorId: string): boolean {
    let current = items.find((account) => account.id === accountId);
    const visited = new Set<string>();
    while (current?.parent_account_id && !visited.has(current.id)) {
      if (current.parent_account_id === ancestorId) return true;
      visited.add(current.id);
      current = items.find((account) => account.id === current!.parent_account_id);
    }
    return false;
  }

  const parentOptions = $derived<ComboOption[]>([
    { id: '', label: 'Akun utama (tanpa parent)' },
    ...items
      .filter(
        (account) =>
          account.id !== editing?.id && (!editing || !isDescendant(account.id, editing.id)),
      )
      .map((account) => ({
        id: account.id,
        label: account.name,
        code: account.code,
        tag: account.is_postable === false ? 'PARENT' : null,
        isFake: account.is_fake,
      })),
  ]);

  function nextAccountCode(parentId: string | null, excludeId?: string): string {
    const siblings = items.filter(
      (account) => (account.parent_account_id ?? null) === parentId && account.id !== excludeId,
    );
    const numericCodes = siblings
      .map((account) => account.code.trim())
      .filter((code) => /^\d+$/.test(code));
    if (numericCodes.length > 0) {
      const lastCode = numericCodes.reduce((max, code) =>
        Number(code) > Number(max) ? code : max,
      );
      return String(Number(lastCode) + 1).padStart(lastCode.length, '0');
    }

    const parent = parentId ? items.find((account) => account.id === parentId) : null;
    if (parent && /^\d+$/.test(parent.code)) return String(Number(parent.code) + 1);

    const rootCodes = items
      .filter((account) => !account.parent_account_id && account.id !== excludeId)
      .map((account) => account.code.trim())
      .filter((code) => /^\d+$/.test(code));
    if (rootCodes.length === 0) return '1000';
    const lastRootCode = rootCodes.reduce((max, code) => (Number(code) > Number(max) ? code : max));
    return String(Number(lastRootCode) + 1).padStart(lastRootCode.length, '0');
  }

  function changeParent(value: string) {
    form.parent_account_id = value || null;
    const parent = value ? items.find((account) => account.id === value) : null;
    if (parent) form.type = parent.type;
    if (creating && codeAutoGenerated) form.code = nextAccountCode(form.parent_account_id);
  }

  async function load() {
    loading = true;
    error = null;
    try {
      items = await accountApi.list('', null, false);
    } catch (e) {
      error = e instanceof Error ? e.message : String(e);
    } finally {
      loading = false;
    }
  }

  onMount(async () => {
    if (!auth.user) {
      const u = await auth.refresh();
      if (!u) {
        goto('/login', { replaceState: true });
        return;
      }
    }
    await load();
  });

  function openCreate() {
    creating = true;
    editing = null;
    codeAutoGenerated = true;
    form = {
      code: nextAccountCode(null),
      name: '',
      description: '',
      type: 'asset',
      normal_balance: 'debit',
      parent_account_id: null,
      is_postable: true,
      is_active: true,
      availability: 'intern',
      legal_basis: '',
    };
    formErrors = null;
  }

  function openEdit(a: Account) {
    creating = false;
    editing = a;
    codeAutoGenerated = false;
    const hasChildren = items.some((account) => account.parent_account_id === a.id);
    form = {
      code: a.code,
      name: a.name,
      description: a.description ?? '',
      type: a.parent_account_id ? (items.find((account) => account.id === a.parent_account_id)?.type ?? a.type) : a.type,
      normal_balance: a.normal_balance,
      parent_account_id: a.parent_account_id,
      is_postable: hasChildren ? false : a.is_postable,
      is_active: a.is_active,
      availability: a.availability,
      legal_basis: a.legal_basis ?? '',
    };
    formErrors = null;
  }

  function closeForm() {
    editing = null;
    creating = false;
    formErrors = null;
    codeAutoGenerated = true;
  }

  async function save() {
    formErrors = null;
    if (form.availability !== 'intern' && !form.legal_basis?.trim()) {
      formErrors = {
        legal_basis: ['Dasar hukum wajib diisi untuk akun Fiskal atau Intern & Fiskal.'],
      };
      return;
    }

    saving = true;
    try {
      if (editing) {
        await accountApi.update(editing.id, form);
      } else {
        await accountApi.create(form);
      }
      closeForm();
      await load();
    } catch (e) {
      if (e instanceof ApiError) {
        const body = e.body as { errors?: Record<string, string[]> } | null;
        formErrors = body?.errors ?? null;
      } else {
        formErrors = { _: [(e as Error).message] };
      }
    } finally {
      saving = false;
    }
  }

  async function destroy(a: Account) {
    if (!confirm(`Hapus akun ${a.code} — ${a.name}?`)) return;
    try {
      await accountApi.destroy(a.id);
      closeForm();
      await load();
    } catch (e) {
      const msg =
        e instanceof ApiError
          ? JSON.stringify((e.body as { errors?: unknown })?.errors ?? e.body)
          : (e as Error).message;
      alert(msg);
    }
  }

  function fieldErr(name: string): string | null {
    return formErrors?.[name]?.[0] ?? null;
  }

  function clearAccountFilters() {
    filterType = '';
    filterNormalBalance = '';
    filterAvailability = '';
    filterStatus = '';
    filterPostable = '';
    filterFake = '';
  }
</script>

