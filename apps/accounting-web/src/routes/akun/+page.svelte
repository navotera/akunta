          {#if activeFilterCount > 0}
            <span
              class="inline-flex h-5 min-w-5 items-center justify-center rounded-full bg-primary px-1 text-[10px] font-bold text-white"
            >
              {activeFilterCount}
            </span>
          {/if}
        </button>
      </div>
    {:else}
      <input
        type="search"
        placeholder="Cari kode, nama, atau deskripsi akun…"
        class="w-72 rounded-md border border-border-default bg-card-bg px-3 py-1.5 text-sm focus:outline-none focus:border-primary"
