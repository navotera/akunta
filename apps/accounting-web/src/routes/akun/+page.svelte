          </svg>
          <input
            type="search"
            placeholder="Cari kode, nama, atau deskripsi akun…"
            class="w-full rounded-md border border-border-default bg-card-bg py-1.5 pl-9 pr-3 text-sm focus:border-primary focus:outline-none"
            bind:value={listSearch}
            data-testid="account-list-search"
          />
        </label>
        <button
          type="button"
          class="relative inline-flex shrink-0 items-center gap-2 rounded-md border border-border-default bg-card-bg px-3 py-1.5 text-sm font-medium text-text-default hover:border-primary hover:text-primary"
