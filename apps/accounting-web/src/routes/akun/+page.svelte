        <thead>
          <tr>
            <th>Kode</th>
            <th>Nama</th>
            <th>Tipe</th>
            <th>Normal</th>
            <th class="text-center">Postable</th>
            <th class="text-center">Aktif</th>
            <th class="text-center">Ketersediaan</th>
          </tr>
        </thead>
        <tbody>
          {#each listFiltered as a (a.id)}
            {@const isParent = items.some((child) => child.parent_account_id === a.id)}
            <tr
              class="group/account cursor-pointer"
              onclick={() => openEdit(a)}
              aria-label={`${a.code} ${a.name}. ${a.description ?? 'Deskripsi akun belum diisi.'}`}
              aria-describedby={`account-description-${a.id}`}
            >
              <td class="font-mono">
